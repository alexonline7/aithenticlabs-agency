const SUPPORTED_LANGS: BlueprintLang[] = ["en", "es", "fr", "pt", "de", "it", "zh", "ja", "ko", "ar", "hi", "ru"];

export function detectBrowserLang(): BlueprintLang {
  const browserLangs = navigator.languages || [navigator.language];
  for (const lang of browserLangs) {
    const code = lang.split("-")[0].toLowerCase() as BlueprintLang;
    if (SUPPORTED_LANGS.includes(code)) return code;
  }
  return "en";
}

export function t(lang: BlueprintLang, key: string): string {
  return translations[lang]?.[key] || translations.en[key] || key;
}
